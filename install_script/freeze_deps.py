"""Freeze LaunchBridge's Python dependencies.

Usage: freeze_deps.py <project_dependencies dir>

Resolves the directory's pyproject.toml with `uv pip compile --universal
--all-extras` and writes, next to it:

  requirements.lock.txt  the full resolved set, kept for the record and the SBOM
  constraints.txt        the `name==version` pins lb-setup installs with (`-c`);
                         git dependencies are left out because pip does not
                         accept URLs as constraints, and are pinned in
                         pyproject.toml instead

It also rewrites every `name @ git+https://...@<ref>` in pyproject.toml to the
commit the lock resolved, so every install gets exactly the code that was
frozen. Commit all three files.

To move a git dependency forward, change its pin in pyproject.toml back to a
branch or tag (e.g. `@main`), run this script, review the diff, and commit.
PyPI packages resolve to the newest versions the ranges allow on every run.
"""

from __future__ import annotations

import re
import shutil
import subprocess  # nosec B404 - runs uv with list-form argv, shell=False
import sys
from pathlib import Path

SHA = re.compile(r"[0-9a-f]{40}")

GENERATED_HEADER = (
    "# Copyright Amazon.com, Inc. or its affiliates. All Rights Reserved.\n"
    "# SPDX-License-Identifier: MIT-0\n"
    "# Generated by install_script/freeze_deps.py. Do not edit; re-run it.\n"
)

# "name[extras] @ git+https://host/path.git@ref" inside a TOML string.
PYPROJECT_VCS = re.compile(
    r'"(?P<name>[A-Za-z0-9._-]+)(?P<extras>\[[^\]]*\])? @ git\+(?P<url>https://[^"@\s]+)@(?P<ref>[^"\s;]+)(?P<rest>[^"]*)"'
)

# "name @ git+https://host/path.git@<sha>" as uv writes it in a lock.
LOCK_VCS = re.compile(
    r"^(?P<name>[A-Za-z0-9._-]+)(?:\[[^\]]*\])? @ git\+(?P<url>https://[^@\s]+)@(?P<sha>[0-9a-f]{40})\b",
    re.M,
)


def normalize(name: str) -> str:
    """PEP 503 name normalisation, so `Foo_Bar` and `foo-bar` compare equal."""
    return re.sub(r"[-_.]+", "-", name).lower()


def pin_vcs_refs(pyproject: str, lock: str) -> tuple[str, list[tuple[str, str, str]]]:
    """Rewrite each git dependency in `pyproject` to the commit `lock` resolved.

    Returns the new text and one (name, ref, sha) tuple per dependency. Raises
    ValueError when a git dependency has no matching resolved commit.
    """
    resolved = {
        (normalize(m["name"]), m["url"]): m["sha"] for m in LOCK_VCS.finditer(lock)
    }
    pins: list[tuple[str, str, str]] = []

    def replace(m: re.Match[str]) -> str:
        key = (normalize(m["name"]), m["url"])
        sha = resolved.get(key)
        if sha is None:
            raise ValueError(
                f"{m['name']} @ {m['url']}: no resolved commit in the lock"
            )
        if SHA.fullmatch(m["ref"]) and m["ref"] != sha:
            raise ValueError(
                f"{m['name']}: pinned to {m['ref']} but the lock resolved {sha}"
            )
        pins.append((m["name"], m["ref"], sha))
        extras = m["extras"] or ""
        return f'"{m["name"]}{extras} @ git+{m["url"]}@{sha}{m["rest"]}"'

    return PYPROJECT_VCS.sub(replace, pyproject), pins


def constraints_from_lock(lock: str) -> str:
    """The lock's `name==version` lines, without git URLs or `# via` comments."""
    lines = []
    for line in lock.splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("#") or " @ " in stripped:
            continue
        lines.append(stripped)
    return "\n".join(lines) + "\n"


def compile_lock(pyproject: Path) -> str:
    uv = shutil.which("uv")
    if uv is None:
        raise RuntimeError(
            "uv is required to freeze dependencies: https://docs.astral.sh/uv/"
        )
    proc = subprocess.run(  # nosec B603 - argv list, shell=False
        [
            uv,
            "pip",
            "compile",
            "--universal",
            "--all-extras",
            "--no-header",
            "--quiet",
            str(pyproject.name),
        ],
        cwd=pyproject.parent,
        capture_output=True,
        text=True,
        check=False,
    )
    if proc.returncode != 0:
        raise RuntimeError(f"uv pip compile failed:\n{proc.stderr}")
    return proc.stdout


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print(__doc__.split("\n\n")[1], file=sys.stderr)
        return 64
    deps_dir = Path(argv[1])
    pyproject = deps_dir / "pyproject.toml"

    try:
        lock = compile_lock(pyproject)
        pinned, pins = pin_vcs_refs(pyproject.read_text(encoding="utf-8"), lock)
    except (RuntimeError, ValueError) as err:
        print(f"ERROR: {err}", file=sys.stderr)
        return 1

    pyproject.write_text(pinned, encoding="utf-8")
    (deps_dir / "requirements.lock.txt").write_text(
        GENERATED_HEADER + lock, encoding="utf-8"
    )
    (deps_dir / "constraints.txt").write_text(
        GENERATED_HEADER + constraints_from_lock(lock), encoding="utf-8"
    )
    for name, ref, sha in pins:
        print(f"  Pinned: {name} @ {ref} -> {sha}")
    print(
        f"  Froze {constraints_from_lock(lock).count(chr(10))} packages into constraints.txt"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
